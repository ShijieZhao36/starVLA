#!/usr/bin/env python3
"""One *mixed* real-data batch, full-model forward/backward; no optimizer.

Run from the production repository with its MRA Python. Input is the trusted
pickle emitted by check_three_source_cpu.py --samples-output. The default
selects one distinct sample per source into the SAME batch (3/2/1 views).
This checks compatibility and finite gradients, not throughput or convergence.
"""
from __future__ import annotations

import argparse
import hashlib
import importlib.metadata
import json
import os
import pickle
import socket
import time
import traceback
from collections import Counter
from datetime import datetime, timezone
from pathlib import Path


EXPECTED = {
    "galaxea_r1lite_stage1": {"views": 3, "valid_dims": 41},
    "libero_plus_rot6d": {"views": 2, "valid_dims": 10},
    "xperience_human": {"views": 1, "valid_dims": 48},
}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--config", type=Path, required=True)
    parser.add_argument("--samples", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--samples-per-source", type=int, default=1)
    parser.add_argument("--skip-prediction", action="store_true")
    args = parser.parse_args()
    assert args.samples_per_source > 0
    args.output.parent.mkdir(parents=True, exist_ok=True)
    result = {
        "status": "running",
        "host": socket.gethostname(),
        "started_at": datetime.now(timezone.utc).isoformat(),
        "config": str(args.config.resolve()),
        "samples": str(args.samples.resolve()),
        "config_sha256": hashlib.sha256(args.config.read_bytes()).hexdigest(),
        "samples_sha256": hashlib.sha256(args.samples.read_bytes()).hexdigest(),
        "optimizer_created": False,
        "optimizer_steps": 0,
        "checkpoint_written": False,
        "cuda_visible_devices": os.environ.get("CUDA_VISIBLE_DEVICES"),
        "stages": [],
    }
    started = time.monotonic()

    def save():
        result["elapsed_seconds"] = round(time.monotonic() - started, 3)
        tmp = args.output.with_suffix(args.output.suffix + ".tmp")
        tmp.write_text(json.dumps(result, indent=2, ensure_ascii=False) + "\n")
        tmp.replace(args.output)

    def stage(name):
        result["stage"] = name
        result["stages"].append({"name": name, "elapsed_seconds": round(time.monotonic() - started, 3)})
        save()
        print(json.dumps({"stage": name, "elapsed_seconds": result["elapsed_seconds"]}), flush=True)

    try:
        stage("imports")
        import numpy as np
        import torch
        from accelerate.utils import set_seed
        from omegaconf import OmegaConf
        from PIL import Image

        from starVLA.model.framework.base_framework import build_framework
        from starVLA.model.framework.share_tools import apply_config_compat

        torch.set_num_threads(4)
        assert torch.cuda.is_available(), "A CUDA GPU is required"
        assert torch.cuda.device_count() == 1, "Set CUDA_VISIBLE_DEVICES to exactly one free GPU"
        result["versions"] = {
            name: importlib.metadata.version(name)
            for name in ("torch", "transformers", "accelerate", "numpy")
        }
        props = torch.cuda.get_device_properties(0)
        result["device"] = {"name": props.name, "total_memory_bytes": props.total_memory}
        cfg = apply_config_compat(OmegaConf.load(args.config))
        assert cfg.framework.name == "QwenPI"
        assert cfg.framework.action_model.decoder_input_norm is True
        assert cfg.framework.action_model.action_dim == 90
        assert cfg.framework.action_model.action_horizon == 8
        assert cfg.datasets.vla_data.include_state is False
        assert cfg.trainer.get("pretrained_checkpoint") is None, "Pretrain smoke must initialize from base VLM"
        assert cfg.trainer.get("freeze_modules", "") in ("", None), "Unexpected freezing: match production explicitly"
        result["seed"] = int(cfg.get("seed", 42))
        result["data_mix"] = cfg.datasets.vla_data.data_mix
        result["production_per_device_batch_size"] = int(cfg.datasets.vla_data.per_device_batch_size)
        stage("load_real_samples")
        # This file is generated by our CPU audit, not downloaded/untrusted input.
        with args.samples.open("rb") as stream:
            available = pickle.load(stream)
        assert isinstance(available, list)
        by_source = {source: [] for source in EXPECTED}
        for sample in available:
            tag = sample["robot_tag"]
            assert tag in EXPECTED, tag
            by_source[tag].append(sample)
        assert all(len(items) >= args.samples_per_source for items in by_source.values()), {
            source: len(items) for source, items in by_source.items()
        }
        # Interleave original samples; never fabricate, pad views, or repeat samples.
        samples = [by_source[source][index] for index in range(args.samples_per_source) for source in EXPECTED]
        result["batch_size"] = len(samples)
        result["sample_counts"] = dict(Counter(sample["robot_tag"] for sample in samples))
        result["sample_details"] = []
        for sample in samples:
            tag = sample["robot_tag"]
            expected = EXPECTED[tag]
            assert len(sample["image"]) == expected["views"], tag
            assert all(isinstance(image, Image.Image) and image.mode == "RGB" for image in sample["image"]), tag
            assert isinstance(sample["lang"], str) and sample["lang"].strip(), tag
            assert "state" not in sample, tag
            action = np.asarray(sample["action"])
            mask = np.asarray(sample["action_mask"])
            assert action.shape == mask.shape == (8, 90), (tag, action.shape, mask.shape)
            assert np.isfinite(action).all() and np.isfinite(mask).all(), tag
            assert np.isin(mask, (0, 1)).all(), tag
            assert np.all(mask.sum(axis=-1) == expected["valid_dims"]), (tag, mask.sum(axis=-1))
            result["sample_details"].append({
                "source": tag,
                "views": len(sample["image"]),
                "image_sizes": [list(image.size) for image in sample["image"]],
                "valid_action_dims": expected["valid_dims"],
                "valid_action_min": float(action[mask == 1].min()),
                "valid_action_max": float(action[mask == 1].max()),
                "masked_action_nonzero_count": int(np.count_nonzero(action[mask == 0])),
            })
        set_seed(result["seed"])
        torch.cuda.reset_peak_memory_stats()
        stage("build_fresh_model")
        model = build_framework(cfg).cuda().train()
        model.zero_grad(set_to_none=True)
        parameter_counts = Counter()
        trainable_counts = Counter()
        for name, param in model.named_parameters():
            group = name.split(".", 1)[0]
            parameter_counts[group] += param.numel()
            if param.requires_grad:
                trainable_counts[group] += param.numel()
        result["parameter_count"] = sum(parameter_counts.values())
        result["trainable_parameter_count"] = sum(trainable_counts.values())
        result["parameter_counts_by_component"] = dict(parameter_counts)
        result["trainable_counts_by_component"] = dict(trainable_counts)
        assert trainable_counts["qwen_vl_interface"] > 0 and trainable_counts["action_model"] > 0
        torch.cuda.synchronize()
        result["model_memory_allocated_bytes"] = torch.cuda.memory_allocated()
        stage("mixed_batch_forward")
        with torch.autocast("cuda", dtype=torch.bfloat16):
            output = model(samples)
            loss = output["action_loss"]
        assert loss.numel() == 1 and torch.isfinite(loss).item(), loss
        result["loss"] = float(loss.detach())
        torch.cuda.synchronize()
        result["forward_peak_memory_allocated_bytes"] = torch.cuda.max_memory_allocated()
        stage("mixed_batch_backward")
        loss.backward()
        torch.cuda.synchronize()
        result["backward_peak_memory_allocated_bytes"] = torch.cuda.max_memory_allocated()
        stage("check_gradients")
        gradient_parameters = Counter()
        gradient_elements = Counter()
        nonzero_gradient_parameters = Counter()
        nonfinite_gradients = []
        for name, param in model.named_parameters():
            if param.grad is None:
                continue
            group = name.split(".", 1)[0]
            grad = param.grad
            gradient_parameters[group] += 1
            gradient_elements[group] += grad.numel()
            if not torch.isfinite(grad).all().item():
                nonfinite_gradients.append(name)
            if torch.count_nonzero(grad).item() > 0:
                nonzero_gradient_parameters[group] += 1
        result["gradient_parameter_counts_by_component"] = dict(gradient_parameters)
        result["gradient_element_counts_by_component"] = dict(gradient_elements)
        result["nonzero_gradient_parameter_counts_by_component"] = dict(nonzero_gradient_parameters)
        result["nonfinite_gradient_names"] = nonfinite_gradients
        assert not nonfinite_gradients, nonfinite_gradients
        for required in ("qwen_vl_interface", "action_model"):
            assert gradient_parameters[required] > 0 and nonzero_gradient_parameters[required] > 0, required
        result["finite_gradients"] = True
        del output, loss
        model.zero_grad(set_to_none=True)
        if not args.skip_prediction:
            stage("mixed_batch_prediction")
            model.eval()
            with torch.inference_mode(), torch.autocast("cuda", dtype=torch.bfloat16):
                prediction = model.predict_action(examples=samples)["normalized_actions"]
            prediction = np.asarray(prediction)
            assert prediction.shape == (len(samples), 8, 90), prediction.shape
            assert np.isfinite(prediction).all()
            for sample, pred in zip(samples, prediction):
                assert np.all(pred[np.asarray(sample["action_mask"]) == 0] == 0), sample["robot_tag"]
            result["prediction_shape"] = list(prediction.shape)
            result["prediction_finite"] = True
            result["masked_prediction_zero"] = True
        torch.cuda.synchronize()
        result["peak_memory_allocated_bytes"] = torch.cuda.max_memory_allocated()
        result["peak_memory_reserved_bytes"] = torch.cuda.max_memory_reserved()
        result["status"] = "passed"
        stage("complete")
    except BaseException as exc:
        result["status"] = "failed"
        result["error"] = f"{type(exc).__name__}: {exc}"
        result["traceback"] = traceback.format_exc()
        save()
        raise
    finally:
        save()
    print(json.dumps(result, indent=2, ensure_ascii=False), flush=True)


if __name__ == "__main__":
    main()
